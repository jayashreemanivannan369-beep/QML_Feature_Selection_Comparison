data = load_breast_cancer()

results = {
    N: {s: {step: {"e": [], "acc": []} for step in STEP_CHECKPOINTS} for s in SOLVERS}
    for N in FEATURE_SIZES
}
times = {N: {s: [] for s in SOLVERS} for N in FEATURE_SIZES}
optimum = {N: [] for N in FEATURE_SIZES}

print("=== RANDOM WALK vs QISKIT QUANTUM WALK BENCHMARK ===")

for N in FEATURE_SIZES:
    k_target = max(1, N // 2)
    print(f"Running N = {N} (k = {k_target}) ...")

    for seed in range(NUM_SEEDS):
        random.seed(seed)
        np.random.seed(seed)

        X_tr_raw, X_te_raw, y_tr, y_te = train_test_split(
            data.data[:, :N], data.target, test_size=0.3,
            random_state=seed, stratify=data.target,
        )
        scaler = StandardScaler().fit(X_tr_raw)
        X_tr, X_te = scaler.transform(X_tr_raw), scaler.transform(X_te_raw)
        X_noisy = X_tr + np.random.normal(0, NOISE_STD, X_tr.shape)

        Q_base, Q = build_qubo(X_noisy, y_tr, k_target)
        A = build_walk_graph(Q_base)
        optimum[N].append(brute_force_optimum(Q, k_target))

        runs = {
            "RandomWalk": run_random_walk(A, Q, k_target, STEP_CHECKPOINTS),
            "QuantumWalk (Qiskit)": run_qiskit_quantum_walk(A, Q, k_target, STEP_CHECKPOINTS),
        }
        for s, (masks, energies, elapsed) in runs.items():
            times[N][s].append(elapsed)
            for step in STEP_CHECKPOINTS:
                acc, _ = evaluate_mask(masks[step], X_tr, X_te, y_tr, y_te)
                results[N][s][step]["e"].append(energies[step])
                results[N][s][step]["acc"].append(acc)


