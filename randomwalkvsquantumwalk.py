# =====================================================================
# STEP 1: QUBO MATRIX
# =====================================================================
def build_qubo(X_noisy, y_train, k_target, penalty_weight=PENALTY_WEIGHT):
    n = X_noisy.shape[1]
    Q_base = np.zeros((n, n))

    for i in range(n):
        corr_y = np.corrcoef(X_noisy[:, i], y_train)[0, 1]
        Q_base[i, i] = -abs(corr_y) if not np.isnan(corr_y) else 0.0

    for i in range(n):
        for j in range(i + 1, n):
            corr_ij = np.corrcoef(X_noisy[:, i], X_noisy[:, j])[0, 1]
            p = 0.5 * abs(corr_ij) if not np.isnan(corr_ij) else 0.0
            Q_base[i, j] = p
            Q_base[j, i] = p

    Q = Q_base.copy()
    for i in range(n):
        Q[i, i] += penalty_weight * (1.0 - 2.0 * k_target)
        for j in range(i + 1, n):
            Q[i, j] += penalty_weight
            Q[j, i] += penalty_weight
    return Q_base, Q


def energy(mask, Q, k_target, penalty_weight=PENALTY_WEIGHT):
    """Energy of a subset of exactly k features."""
    v = np.array(mask)
    return float(v @ Q @ v) + penalty_weight * (k_target ** 2)


def brute_force_optimum(Q, k_target):
    """Brute-force reference line to track true best QUBO energy."""
    n = Q.shape[0]
    best = np.inf
    for subset in combinations(range(n), k_target):
        mask = np.zeros(n, dtype=int)
        mask[list(subset)] = 1
        best = min(best, energy(mask, Q, k_target))
    return best


def build_walk_graph(Q_base):
    """Constructs shared affinity graph for both classical and quantum walks."""
    n = Q_base.shape[0]
    rel = -np.diag(Q_base)
    A = np.zeros((n, n))
    for i in range(n):
        for j in range(n):
            if i != j:
                A[i, j] = np.exp((rel[i] + rel[j]) / 2.0 - Q_base[i, j])
    return A


def top_k_mask(scores, k_target):
    idx = np.argsort(scores)[-k_target:]
    mask = np.zeros(len(scores), dtype=int)
    mask[idx] = 1
    return mask


# =====================================================================
# CLASSICAL RANDOM WALK
# =====================================================================
def run_random_walk(A, Q, k_target, checkpoints):
    t0 = time.time()
    n = A.shape[0]
    P = A / A.sum(axis=1, keepdims=True)

    state = np.ones(n) / n
    running = np.zeros(n)
    masks, energies = {}, {}

    for step in range(1, max(checkpoints) + 1):
        state = state @ P
        running += state
        if step in checkpoints:
            masks[step] = top_k_mask(running / step, k_target)
            energies[step] = energy(masks[step], Q, k_target)

    return masks, energies, time.time() - t0


# =====================================================================
# QUANTUM WALK (Qiskit Statevector & Quantum Circuit Simulation)
# =====================================================================
def run_qiskit_quantum_walk(A, Q, k_target, checkpoints):
    t0 = time.time()
    n = A.shape[0]

    # Calculate number of qubits needed (2^num_qubits >= n)
    num_qubits = int(np.ceil(np.log2(n)))
    dim_padded = 1 << num_qubits

    # 1. Build transition probability matrix
    P = A / A.sum(axis=1, keepdims=True)
    P_pad = np.zeros((dim_padded, dim_padded))
    P_pad[:n, :n] = P

    # 2. Discriminant matrix D = sqrt(P * P^T)
    D = np.sqrt(P_pad * P_pad.T)
    eigvals, eigvecs = np.linalg.eigh(D)
    theta = np.arccos(np.clip(eigvals, -1.0, 1.0))

    # 3. Create initial Qiskit Quantum Circuit (Equal superposition over qubits)
    qc_init = QuantumCircuit(num_qubits)
    qc_init.h(range(num_qubits))

    # Convert circuit to Qiskit Statevector amplitude array
    psi0 = Statevector.from_instruction(qc_init).data
    coeffs = eigvecs.T @ psi0

    running = np.zeros(n)
    masks, energies = {}, {}

    # 4. Simulate step-by-step quantum state evolution
    for step in range(1, max(checkpoints) + 1):
        # State vector evolution under walk operator phases
        psi_t = eigvecs @ (np.cos(step * theta) * coeffs)
        probs = np.abs(psi_t[:n]) ** 2
        probs = probs / probs.sum()
        running += probs

        if step in checkpoints:
            masks[step] = top_k_mask(running / step, k_target)
            energies[step] = energy(masks[step], Q, k_target)

    return masks, energies, time.time() - t0


# =====================================================================
# DOWNSTREAM ML EVALUATION
# =====================================================================
def evaluate_mask(mask, X_train, X_test, y_train, y_test):
    selected = [i for i, bit in enumerate(mask) if bit == 1]
    if len(selected) == 0:
        return np.nan, np.nan
    clf = LogisticRegression(max_iter=1000).fit(X_train[:, selected], y_train)
    preds = clf.predict(X_test[:, selected])
    return accuracy_score(y_test, preds), f1_score(y_test, preds)


