FEATURE_SIZES = [4, 8, 12, 15]
NUM_SEEDS = 10
NOISE_STD = 0.05

# Permutation-importance cost controls. BOTH methods use the same values.
PERM_REPEATS = 1          # times each feature is shuffled (was 3)
SCORING_ROWS = 100        # training rows used to measure the accuracy drop (was all ~398)

# Kernel settings
VERIFY_WITH_QISKIT = True          # check the fast kernel against Qiskit at start-up
USE_QISKIT_FOR_ALL_STATES = False  # True = use Qiskit for every state (exact but VERY slow)

METHODS = ("RFE (RBF-SVM)", "QSVM-RFE (ZZFeatureMap kernel)")
BASELINE = "All N features"


# =====================================================================
# FAST EXACT SIMULATION OF Qiskit's ZZFeatureMap(reps=2, entanglement="full")
# Each repetition = Hadamard on every qubit, then a diagonal phase layer:
#   phase(b) = exp( i * [ sum_i 2*x_i*b_i  +  sum_{i<j} 2*(pi-x_i)*(pi-x_j)*(b_i XOR b_j) ] )
# This is the same circuit Qiskit builds, simulated with NumPy instead of
# gate by gate, so it is many times faster. It is checked against Qiskit below.
# =====================================================================
class ZZKernelSimulator:
    def __init__(self, n, reps=2):
        self.n, self.reps, self.dim = n, reps, 1 << n
        idx = np.arange(self.dim)
        self.bits = ((idx[:, None] >> np.arange(n)) & 1).astype(np.float64)
        self.pairs = list(combinations(range(n), 2))
        if self.pairs:
            self.xor = np.stack(
                [(self.bits[:, i] != self.bits[:, j]) for i, j in self.pairs], axis=1
            ).astype(np.float64)
        else:
            self.xor = np.zeros((self.dim, 0))

    def _hadamard_all(self, psi):
        c = psi.shape[0]
        psi = psi.reshape((c,) + (2,) * self.n)
        for ax in range(1, self.n + 1):
            a = np.take(psi, 0, axis=ax)
            b = np.take(psi, 1, axis=ax)
            psi = np.stack((a + b, a - b), axis=ax) / np.sqrt(2.0)
        return psi.reshape(c, -1)

    def states(self, X, chunk=64):
        out = np.empty((X.shape[0], self.dim), dtype=np.complex128)
        for s in range(0, X.shape[0], chunk):
            Xc = X[s:s + chunk]
            theta = (2.0 * Xc) @ self.bits.T
            if self.pairs:
                pair = np.stack(
                    [2.0 * (np.pi - Xc[:, i]) * (np.pi - Xc[:, j]) for i, j in self.pairs], axis=1
                )
                theta += pair @ self.xor.T
            phase = np.exp(1j * theta)
            psi = np.zeros((Xc.shape[0], self.dim), dtype=np.complex128)
            psi[:, 0] = 1.0
            for _ in range(self.reps):
                psi = phase * self._hadamard_all(psi)
            out[s:s + chunk] = psi
        return out


_sim_cache = {}


def qiskit_states(X):
    """Slow path: build and simulate one Qiskit circuit per sample."""
    from qiskit.circuit.library import ZZFeatureMap
    from qiskit.quantum_info import Statevector
    fm = ZZFeatureMap(feature_dimension=X.shape[1], reps=2, entanglement="full")
    return np.array([Statevector.from_instruction(fm.assign_parameters(x)).data for x in X])


def get_states(X):
    """Quantum states for every row of X (one row = one data point)."""
    if USE_QISKIT_FOR_ALL_STATES:
        return qiskit_states(X)
    n = X.shape[1]
    if n not in _sim_cache:
        _sim_cache[n] = ZZKernelSimulator(n)
    return _sim_cache[n].states(X)


def gram(states_a, states_b):
    """Fidelity kernel K_ij = |<phi(a_i)|phi(b_j)>|^2."""
    return np.abs(states_a.conj() @ states_b.T) ** 2


def verify_against_qiskit():
    try:
        qiskit_states(np.zeros((1, 2)))
    except ImportError:
        print("Qiskit is not installed here, so the Qiskit check was skipped.")
        return
    rng = np.random.default_rng(0)
    worst = 0.0
    for n in (3, 4, 6):
        X = rng.uniform(-2.5, 2.5, (5, n))
        q = qiskit_states(X)
        f = ZZKernelSimulator(n).states(X)
        worst = max(worst, np.abs(gram(q, q) - gram(f, f)).max())
    print(f"Check against Qiskit's ZZFeatureMap: largest kernel difference = {worst:.2e}")
    if worst > 1e-6:
        raise RuntimeError(
            "The fast kernel does NOT match Qiskit. Set USE_QISKIT_FOR_ALL_STATES = True "
            "(slow) or send me this message."
        )


def to_mask(selected, n_features):
    return [1 if i in selected else 0 for i in range(n_features)]


# =====================================================================
# FEATURE SELECTION
# BOTH methods rank features the SAME way: shuffle one feature and see how
# much the model's accuracy drops (permutation importance).
# Only the kernel differs: RBF (classical) vs ZZFeatureMap quantum kernel.
#
# SPEED-UPS (same for both methods):
#  * the quantum states of the training data are computed ONCE per RFE step
#    and re-used (the old code recomputed them for every shuffle);
#  * the accuracy drop is measured on SCORING_ROWS rows, not all of them.
# =====================================================================
def run_permutation_rfe(X, y, k_target, kind, seed, score_idx):
    t0 = time.time()
    n = X.shape[1]
    rng = np.random.default_rng(seed)       # same shuffling stream for both methods
    y_score = y[score_idx]
    cur = list(range(n))

    while len(cur) > k_target:
        Xs = X[:, cur]

        if kind == "rbf":
            clf = SVC(kernel="rbf").fit(Xs, y)
            base_pred = clf.predict(Xs[score_idx])
            predict_rows = lambda Z: clf.predict(Z)
        else:
            S_train = get_states(Xs)                     # computed once per step
            K_train = gram(S_train, S_train)
            clf = SVC(kernel="precomputed").fit(K_train, y)
            base_pred = clf.predict(K_train[score_idx])
            predict_rows = lambda Z: clf.predict(gram(get_states(Z), S_train))

        base_acc = accuracy_score(y_score, base_pred)
        importance = []
        for f in range(len(cur)):
            drops = []
            for _ in range(PERM_REPEATS):
                Z = Xs[score_idx].copy()
                Z[:, f] = rng.permutation(Z[:, f])
                drops.append(base_acc - accuracy_score(y_score, predict_rows(Z)))
            importance.append(np.mean(drops))
        cur.pop(int(np.argmin(importance)))

    return to_mask(cur, n), time.time() - t0


# =====================================================================
# EVALUATION (same final classifier for every method)
# Hinge loss is measured on TRAINING data (fit quality). Accuracy/F1 are test.
# =====================================================================
def evaluate_mask(mask, X_train, X_test, y_train, y_test):
    selected = [i for i, bit in enumerate(mask) if bit == 1]
    if len(selected) == 0:
        return np.nan, np.nan, np.nan
    clf = SVC(kernel="rbf").fit(X_train[:, selected], y_train)
    preds = clf.predict(X_test[:, selected])
    dec = clf.decision_function(X_train[:, selected])
    hinge = float(np.mean(np.maximum(0, 1 - y_train * dec)))
    return hinge, accuracy_score(y_test, preds), f1_score(y_test, preds)


