if VERIFY_WITH_QISKIT:
    verify_against_qiskit()

data = load_breast_cancer()
names = list(METHODS) + [BASELINE]
raw = {N: {s: {"loss": [], "t": [], "acc": [], "f1": []} for s in names} for N in FEATURE_SIZES}

print("=== RFE vs QSVM-RFE (ZZFeatureMap quantum kernel) BENCHMARK ===")
run_start = time.time()

for N in FEATURE_SIZES:
    k_target = max(1, N // 2)
    print(f"Running N = {N} (k = {k_target}) ...", flush=True)

    for seed in range(NUM_SEEDS):
        random.seed(seed)
        np.random.seed(seed)

        X_tr_raw, X_te_raw, y_tr, y_te = train_test_split(
            data.data[:, :N], data.target, test_size=0.3,
            random_state=seed, stratify=data.target,
        )
        scaler = StandardScaler().fit(X_tr_raw)
        X_tr, X_te = scaler.transform(X_tr_raw), scaler.transform(X_te_raw)

        # Noise goes into the data used for CHOOSING features only.
        X_noisy = X_tr + np.random.normal(0, NOISE_STD, X_tr.shape)
        y_tr_s = np.where(y_tr == 0, -1, 1)
        y_te_s = np.where(y_te == 0, -1, 1)

        # Same scoring rows for both methods
        n_score = min(SCORING_ROWS, len(y_tr_s))
        score_idx = np.sort(np.random.default_rng(1000 + seed).choice(len(y_tr_s), n_score, replace=False))

        runs = {
            METHODS[0]: run_permutation_rfe(X_noisy, y_tr_s, k_target, "rbf", seed, score_idx),
            METHODS[1]: run_permutation_rfe(X_noisy, y_tr_s, k_target, "quantum", seed, score_idx),
            BASELINE: ([1] * N, 0.0),
        }
        for name, (mask, elapsed) in runs.items():
            loss, acc, f1 = evaluate_mask(mask, X_tr, X_te, y_tr_s, y_te_s)
            raw[N][name]["loss"].append(loss)
            raw[N][name]["t"].append(elapsed)
            raw[N][name]["acc"].append(acc)
            raw[N][name]["f1"].append(f1)

        print(f"   seed {seed + 1}/{NUM_SEEDS} done ({time.time() - run_start:.0f}s since start)", flush=True)


